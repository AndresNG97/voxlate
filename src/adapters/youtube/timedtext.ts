/** Parser de las respuestas de /api/timedtext de YouTube (json3, srv1, srv3) → frases. */
import type { Cue } from '@/core/domain/cue';
import { plausibleSpeechEnd, wordDurationMs, type TimedWord } from '@/core/domain/timing';

interface Json3Seg {
  utf8?: string;
  tOffsetMs?: number;
}
interface Json3Event {
  tStartMs?: number;
  dDurationMs?: number;
  segs?: Json3Seg[];
  aAppend?: number;
}

/**
 * Convierte la respuesta de /api/timedtext de YouTube en frases.
 * Soporta json3 (lo que pide el reproductor web) y XML (srv1/srv3) por si acaso.
 */
export function parseTimedText(body: string, isAutoGenerated: boolean): Cue[] {
  const trimmed = body.trimStart();
  if (!trimmed) return [];
  if (trimmed.startsWith('{')) {
    const events = parseJson3(trimmed);
    return isAutoGenerated ? resegmentAsr(wordsOf(events)) : withSpeechEnd(json3ToCues(events));
  }
  return withSpeechEnd(xmlToCues(trimmed));
}

/** Palabras de una pista automática (json3) con el instante en que empieza cada una. */
export function parseAsrWords(body: string): TimedWord[] {
  const trimmed = body.trimStart();
  return trimmed.startsWith('{') ? wordsOf(parseJson3(trimmed)) : [];
}

function parseJson3(body: string): Json3Event[] {
  return (JSON.parse(body) as { events?: Json3Event[] }).events ?? [];
}

/**
 * Subtítulos manuales sin otra referencia: el habla termina, como mucho, al
 * final del bloque o cuando empieza el siguiente. Es una aproximación pobre
 * (los bloques incluyen silencios); si hay automáticos, alignToWords la mejora.
 */
function withSpeechEnd(cues: Cue[]): Cue[] {
  return cues.map((c, i) => ({ ...c, timing: 'block', speechEnd: Math.min(c.end, cues[i + 1]?.start ?? Infinity) }));
}

/**
 * Quita lo que no se dice: anotaciones de sonido o de quién habla, como
 * "(Laughter)", "[Music]", "(Audience)" o "♪". Si no queda nada, la frase se descarta.
 */
function cleanText(s: string): string {
  return s
    .replace(/\[[^\]]*\]|\([^)]*\)|[♪♫]/g, ' ')
    .replace(/^\s*(>>|-)\s*/, '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

function json3ToCues(events: Json3Event[]): Cue[] {
  const cues: Cue[] = [];
  for (const ev of events) {
    if (!ev.segs || ev.aAppend) continue;
    const text = cleanText(ev.segs.map((s) => s.utf8 ?? '').join(''));
    if (!text) continue;
    const start = ev.tStartMs ?? 0;
    cues.push({ start, end: start + (ev.dDurationMs ?? 2000), text });
  }
  return mergeBrokenSentences(cues);
}

/**
 * Los subtítulos manuales suelen cortar una frase en 2-3 bloques. Traducir
 * medias frases da resultados malos, así que unimos bloques consecutivos
 * cuando el anterior no termina en puntuación y la unión no es demasiado larga.
 */
function mergeBrokenSentences(cues: Cue[]): Cue[] {
  const out: Cue[] = [];
  for (const cue of cues) {
    const prev = out[out.length - 1];
    if (
      prev &&
      !/[.!?…:;"')\]]$/.test(prev.text) &&
      cue.start - prev.end < 400 &&
      prev.end - prev.start < 6000 &&
      (prev.text + ' ' + cue.text).length < 140
    ) {
      prev.text = `${prev.text} ${cue.text}`;
      prev.end = Math.max(prev.end, cue.end);
    } else {
      out.push({ ...cue });
    }
  }
  return out;
}

/**
 * Los automáticos (ASR) llegan palabra a palabra en ventanas que se van
 * desplazando. Reconstruimos el flujo de palabras con su instante de inicio.
 * Las anotaciones ("[Music]") se descartan.
 */
function wordsOf(events: Json3Event[]): TimedWord[] {
  const words: TimedWord[] = [];
  const starts = events.filter((e) => e.segs).map((e) => e.tStartMs ?? 0);
  for (const ev of events) {
    if (!ev.segs) continue;
    const base = ev.tStartMs ?? 0;
    // Hasta cuándo puede durar el último trozo del evento: su fin o el siguiente evento.
    const nextEvent = starts.find((t) => t > base) ?? Infinity;
    const eventEnd = Math.min(base + (ev.dDurationMs ?? 0) || Infinity, nextEvent);
    ev.segs.forEach((seg, k) => {
      const text = cleanText(seg.utf8 ?? '');
      if (!text) return;
      const t0 = base + (seg.tOffsetMs ?? 0);
      const tokens = text.split(' ');
      if (tokens.length === 1) {
        words.push({ t: t0, w: text });
        return;
      }
      // Algunas pistas automáticas no dan el tiempo de cada palabra sino de trozos
      // de frase: repartimos sus palabras en lo que dura el trozo, según su longitud.
      const nextSeg = ev.segs![k + 1];
      const t1 = nextSeg ? base + (nextSeg.tOffsetMs ?? 0) : eventEnd;
      const span = Number.isFinite(t1) && t1 > t0 ? t1 - t0 : tokens.length * 300;
      const total = tokens.reduce((n, w) => n + w.length + 1, 0);
      let acc = 0;
      for (const w of tokens) {
        words.push({ t: Math.round(t0 + (span * acc) / total), w });
        acc += w.length + 1;
      }
    });
  }
  return words.sort((a, b) => a.t - b.t);
}

/** Pausa que, por sí sola, cierra una frase. */
const LONG_PAUSE_MS = 700;
/** Pausa que cierra la frase si ya es razonablemente larga. */
const SHORT_PAUSE_MS = 300;
const MIN_WORDS_FOR_SHORT_PAUSE = 8;
const MAX_WORDS = 22;
const MAX_DURATION_MS = 7000;

/**
 * Corta el flujo de palabras automáticas en frases. Suelen venir sin
 * puntuación, así que nos guiamos por las pausas reales de la persona: una
 * pausa larga siempre corta; una corta, si la frase ya tiene cierta longitud.
 * Así no partimos frases por la mitad (malo para traducir) ni hacemos bloques enormes.
 */
function resegmentAsr(words: TimedWord[]): Cue[] {
  const cues: Cue[] = [];
  let cur: TimedWord[] = [];
  const flush = (end: number, nextWordAt: number) => {
    if (!cur.length) return;
    const first = cur[0]!;
    const last = cur[cur.length - 1]!;
    // Tenemos el inicio de cada palabra: el habla acaba al terminar la última.
    const text = cur.map((x) => x.w).join(' ');
    const speechEnd = Math.min(
      Math.max(last.t + wordDurationMs(last.w), plausibleSpeechEnd(first.t, text)),
      nextWordAt,
      end,
    );
    cues.push({ start: first.t, speechStart: first.t, end, speechEnd, timing: 'words', text });
    cur = [];
  };

  for (let i = 0; i < words.length; i++) {
    const word = words[i]!;
    const next = words[i + 1];
    cur.push(word);
    const gap = next ? next.t - word.t - wordDurationMs(word.w) : Infinity;
    const duration = word.t - cur[0]!.t;
    const endsSentence = /[.!?…]$/.test(word.w);
    if (
      endsSentence ||
      gap > LONG_PAUSE_MS ||
      (gap > SHORT_PAUSE_MS && cur.length >= MIN_WORDS_FOR_SHORT_PAUSE) ||
      cur.length >= MAX_WORDS ||
      duration > MAX_DURATION_MS
    ) {
      flush(next ? Math.min(next.t, word.t + 1500) : word.t + 1500, next?.t ?? Infinity);
    }
  }
  return cues;
}

function xmlToCues(xml: string): Cue[] {
  const doc = new DOMParser().parseFromString(xml, 'text/xml');
  const cues: Cue[] = [];
  // srv1: <text start="1.2" dur="3.4">  ·  srv3: <p t="1200" d="3400">
  doc.querySelectorAll('text').forEach((n) => {
    const start = parseFloat(n.getAttribute('start') ?? '0') * 1000;
    const dur = parseFloat(n.getAttribute('dur') ?? '2') * 1000;
    const text = cleanText(n.textContent ?? '');
    if (text) cues.push({ start, end: start + dur, text });
  });
  doc.querySelectorAll('p').forEach((n) => {
    const start = parseInt(n.getAttribute('t') ?? '0', 10);
    const dur = parseInt(n.getAttribute('d') ?? '2000', 10);
    const text = cleanText(n.textContent ?? '');
    if (text) cues.push({ start, end: start + dur, text });
  });
  return mergeBrokenSentences(cues.sort((a, b) => a.start - b.start));
}
